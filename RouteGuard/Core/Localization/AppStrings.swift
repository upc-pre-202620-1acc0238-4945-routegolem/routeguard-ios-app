import Foundation
import Observation

enum AppLanguage: String, CaseIterable {
    case spanish = "es"
    case english = "en"

    var displayName: String {
        switch self {
        case .spanish: return "Español (ES)"
        case .english: return "English (EN)"
        }
    }
}

@Observable
final class AppStrings {
    static let shared = AppStrings()

    var currentLanguage: AppLanguage = .spanish

    private init() {
        let saved = UserDefaults.standard.string(forKey: "rg_app_language")
        if let saved, let lang = AppLanguage(rawValue: saved) {
            currentLanguage = lang
        }
    }

    func setLanguage(_ language: AppLanguage) {
        currentLanguage = language
        UserDefaults.standard.set(language.rawValue, forKey: "rg_app_language")
    }

    static func tr(_ key: String) -> String {
        let lang = shared.currentLanguage
        return dictionaries[lang]?[key] ?? dictionaries[.spanish]?[key] ?? key
    }

    static func trf(_ key: String, _ params: [String: String]) -> String {
        var result = tr(key)
        for (k, v) in params {
            result = result.replacingOccurrences(of: "{\(k)}", with: v)
        }
        return result
    }

    static func keys(for language: AppLanguage) -> Set<String> {
        dictionaries[language].map { Set($0.keys) } ?? []
    }

